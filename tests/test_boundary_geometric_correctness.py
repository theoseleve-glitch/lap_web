"""Day 8.5 Phase A5 — geometric correctness of the assembled boundary mesh.

Day 8 (Gate-8) verified width MAGNITUDE: max ≤ 12m, 0 out-of-range bins.
That was insufficient: the OK_R4 mesh is geometrically twisted (visual
"snake-like ribbon" + pinch-to-fan sections) even though widths-per-bin
all pass magnitude checks.

These tests add geometric-correctness gates that catch the failure mode
Day 8's gates missed:

  G1. Polygon assembled from (left_boundary + reversed right_boundary)
      must be a valid, simple closed loop (no self-intersections).

  G2. Per-bin total width (left + right) must be ≥ some minimum (e.g.,
      1m) on the bulk of the track. Sustained "pinches" (width < 0.5m
      across > 20 consecutive bins) indicate boundary collapse.

  G3. Adjacent-bin width derivative must stay bounded. |d(width_left)/ds|
      and |d(width_right)/ds| > 1.0 /m at any bin indicates a per-bin
      discontinuity that produces visual artifacts.

  G4. No bin where the rendered LEFT point is closer to gt RIGHT than
      to gt LEFT (and vice versa). Crossings indicate mesh sides are
      swapped at those bins.

The test runs on the actual OK_R4 mesh artifact regenerated by
scripts/generate_mesh.py, and on KCT_R1 (regression check — KCT
worked visually at Day 8 close, must still pass).

Committed FAILING on OK_R4 post-Day-8 as a Day-8 gap-marker.
"""
from __future__ import annotations

import json
import os
import sys
import tempfile
from pathlib import Path

import numpy as np
import pytest

_REPO_ROOT = Path(__file__).resolve().parent.parent
_TELEMETRY_PKG = _REPO_ROOT / "telemetry_tool"
for _p in (_REPO_ROOT, _TELEMETRY_PKG):
    if str(_p) not in sys.path:
        sys.path.insert(0, str(_p))


def _resolve_csv(session: str) -> Path | None:
    """Find a session CSV across tree layouts.

    Checks (in order):
      1. ``$LAP_DATA_RAW`` env override (absolute path to data/raw dir).
      2. ``<repo>/data/raw/<session>`` — V2 layout.
      3. ``<repo>/../Analysis/V2_claude_ai/data/raw/<session>`` —
         lap_web tree falling back to V2 sibling for test fixtures.
    """
    env = os.environ.get("LAP_DATA_RAW")
    candidates: list[Path] = []
    if env:
        candidates.append(Path(env) / session)
    candidates.append(_REPO_ROOT / "data" / "raw" / session)
    candidates.append(_REPO_ROOT.parent / "Analysis" / "V2_claude_ai" / "data" / "raw" / session)
    for c in candidates:
        if c.exists():
            return c
    return None


def _generate_mesh_if_needed(session: str, track: str) -> Path:
    """Ensure a mesh JSON exists at %TEMP%/mesh_<track>_day8repro.json;
    regenerate via scripts/generate_mesh.py if missing.

    Skips the test with pytest.skip if the source CSV is not findable
    (relevant when running in lap_web's tree without test fixtures wired
    locally — set $LAP_DATA_RAW to bypass)."""
    tmp = Path(tempfile.gettempdir())
    out = tmp / f"mesh_{track}_day8repro.json"
    if not out.exists():
        csv_path = _resolve_csv(session)
        if csv_path is None:
            pytest.skip(
                f"Test fixture {session} not found in any expected location; "
                f"set $LAP_DATA_RAW to override"
            )
        import subprocess
        cmd = [
            sys.executable,
            str(_REPO_ROOT / "scripts" / "generate_mesh.py"),
            "--session", str(csv_path),
            "--track", track,
            "--output", str(out),
            "--log-level", "WARNING",
        ]
        subprocess.run(cmd, check=True, cwd=str(_REPO_ROOT))
    return out


def _load_mesh(path: Path) -> dict:
    with open(path) as f:
        return json.load(f)


# ── G1: assembled polygon must be valid + simple ───────────────────────


def _polygon_from_mesh(mesh: dict):
    """Build closed polygon: left_boundary forward + right_boundary reversed."""
    from shapely.geometry import Polygon
    lx = mesh["left_boundary"]["x_m"]
    ly = mesh["left_boundary"]["y_m"]
    rx = mesh["right_boundary"]["x_m"]
    ry = mesh["right_boundary"]["y_m"]
    left = list(zip(lx, ly))
    right_rev = list(zip(rx[::-1], ry[::-1]))
    return Polygon(left + right_rev)


def test_ok_r4_assembled_polygon_is_simple_and_valid():
    """G1: assembled mesh polygon on OK_R4 must be valid + simple
    (no self-intersections)."""
    mesh = _load_mesh(_generate_mesh_if_needed("OK_R4.csv", "ok"))
    poly = _polygon_from_mesh(mesh)
    assert poly.is_valid, (
        f"OK_R4 assembled polygon is not valid: {poly.is_valid_reason if hasattr(poly, 'is_valid_reason') else 'shapely_invalid'}"
    )
    assert poly.is_simple, (
        "OK_R4 assembled polygon is not simple (self-intersecting). "
        "This is the snake-like twisted ribbon failure mode."
    )


def test_kct_r1_assembled_polygon_is_simple_and_valid():
    """G1 regression: KCT_R1 polygon must be valid + simple."""
    mesh = _load_mesh(_generate_mesh_if_needed("KCT_R1.csv", "kct"))
    poly = _polygon_from_mesh(mesh)
    assert poly.is_valid
    assert poly.is_simple, "KCT_R1 mesh polygon is not simple — regression"


# ── G2: no sustained pinches ───────────────────────────────────────────


def _per_bin_widths(mesh: dict) -> tuple[np.ndarray, np.ndarray]:
    clx = np.asarray(mesh["centerline"]["x_m"])
    cly = np.asarray(mesh["centerline"]["y_m"])
    lx = np.asarray(mesh["left_boundary"]["x_m"])
    ly = np.asarray(mesh["left_boundary"]["y_m"])
    rx = np.asarray(mesh["right_boundary"]["x_m"])
    ry = np.asarray(mesh["right_boundary"]["y_m"])
    return np.hypot(lx - clx, ly - cly), np.hypot(rx - clx, ry - cly)


def _longest_run(mask: np.ndarray) -> int:
    """Longest run of True values in a boolean mask."""
    if mask.size == 0:
        return 0
    runs = np.diff(np.concatenate(([0], mask.astype(int), [0])))
    starts = np.where(runs == 1)[0]
    ends = np.where(runs == -1)[0]
    return int((ends - starts).max()) if len(starts) else 0


_PINCH_RUN_LIMIT_BINS = 70
"""Maximum allowed run of consecutive bins with width < 0.5m. Real
narrow features (S1 tail on OK, hairpin apexes on KCT) can legitimately
hold ≤50 bins (25m) of sub-0.5m width per D3 lock; the Day-8.5 hot-patch
target was eliminating the SEAM coverage-gap collapse (80+ bins on
OK_R4 RIGHT pre-fix, since the polyline endpoints both projected to
s ≈ L not bracketing the seam). 70 bins gives the seam-collapse bug
clear room to fail while accepting real narrow geometry."""


def test_ok_r4_no_sustained_width_pinch():
    """G2: no run of > 70 consecutive bins (35m) with width < 0.5m. A
    localized 1-2-bin pinch is a real tight feature (apex). A sustained
    pinch over 35m at the SEAM specifically (s ≈ 0 or s ≈ L) indicates
    coverage-gap collapse — the Day-8 → Day-8.5 hot-patch target."""
    mesh = _load_mesh(_generate_mesh_if_needed("OK_R4.csv", "ok"))
    dL, dR = _per_bin_widths(mesh)
    pinch_L = _longest_run(dL < 0.5)
    pinch_R = _longest_run(dR < 0.5)
    assert pinch_L < _PINCH_RUN_LIMIT_BINS, (
        f"OK_R4 LEFT has {pinch_L} consecutive bins with width < 0.5m — "
        "sustained boundary collapse (exceeds real-apex tolerance)"
    )
    assert pinch_R < _PINCH_RUN_LIMIT_BINS, (
        f"OK_R4 RIGHT has {pinch_R} consecutive bins with width < 0.5m — "
        "sustained boundary collapse (exceeds real-apex tolerance)"
    )


def test_ok_r4_no_seam_pinch():
    """G2-seam: no pinch in the first 30 bins (15m) or last 30 bins of
    the centerline. The seam region (s ≈ 0 ≈ L) should NEVER pinch —
    if it does, the polyline coverage-gap collapse bug is back."""
    mesh = _load_mesh(_generate_mesh_if_needed("OK_R4.csv", "ok"))
    dL, dR = _per_bin_widths(mesh)
    SEAM_BINS = 30
    assert (dL[:SEAM_BINS] >= 0.5).all() and (dL[-SEAM_BINS:] >= 0.5).all(), (
        "OK_R4 LEFT has a pinch in the seam region (first/last 15m of s) — "
        "polyline coverage-gap collapse regression"
    )
    assert (dR[:SEAM_BINS] >= 0.5).all() and (dR[-SEAM_BINS:] >= 0.5).all(), (
        "OK_R4 RIGHT has a pinch in the seam region (first/last 15m of s) — "
        "polyline coverage-gap collapse regression"
    )


def test_kct_r1_no_sustained_width_pinch():
    """G2 regression: KCT_R1 must not have a SEAM-collapse pinch.
    Real apex pinches are tolerated up to _PINCH_RUN_LIMIT_BINS."""
    mesh = _load_mesh(_generate_mesh_if_needed("KCT_R1.csv", "kct"))
    dL, dR = _per_bin_widths(mesh)
    assert _longest_run(dL < 0.5) < _PINCH_RUN_LIMIT_BINS
    assert _longest_run(dR < 0.5) < _PINCH_RUN_LIMIT_BINS


def test_kct_r1_no_seam_pinch():
    """G2-seam regression: KCT seam must not pinch."""
    mesh = _load_mesh(_generate_mesh_if_needed("KCT_R1.csv", "kct"))
    dL, dR = _per_bin_widths(mesh)
    SEAM_BINS = 30
    assert (dL[:SEAM_BINS] >= 0.5).all() and (dL[-SEAM_BINS:] >= 0.5).all()
    assert (dR[:SEAM_BINS] >= 0.5).all() and (dR[-SEAM_BINS:] >= 0.5).all()


# ── G5: seam elevation continuity ──────────────────────────────────────


_SEAM_ELEV_TOLERANCE_M = 0.10
"""Seam elevation gap tolerance (z[0] − z[-1] on closed-loop centerline).
GPS altimetry noise floor is ~0.5 m per sample; with multi-lap averaging
+ wrap-padded smoothing, the seam gap should converge to ≤ 10 cm.
Day-9 hot-patch: pre-fix, OK_R4 had 23 cm gap from reflect-padded smoothing
on closed-loop elevation data. Standing gate to prevent regression."""


def test_ok_r4_no_seam_elevation_step():
    """G5: closed-loop centerline elevation must be continuous at the seam.

    Reflect-padding smoothing on elevation produces a step at the seam
    because both endpoints get averaged with their own mirrored values
    instead of with the actual track-wrapped values. Wrap padding
    (post-Day-9 hot-patch) closes the gap.
    """
    import numpy as np
    mesh = _load_mesh(_generate_mesh_if_needed("OK_R4.csv", "ok"))
    elev = np.asarray(mesh["centerline"]["z_m"])
    seam_gap = float(elev[0] - elev[-1])
    assert abs(seam_gap) <= _SEAM_ELEV_TOLERANCE_M, (
        f"OK_R4 seam elevation gap = {seam_gap:+.3f} m exceeds "
        f"tolerance {_SEAM_ELEV_TOLERANCE_M} m — closed-loop smoothing "
        "regression. Check that _smooth_1d uses wrap padding."
    )


def test_kct_r1_no_seam_elevation_step():
    """G5 regression: KCT_R1 seam elevation must also stay continuous."""
    import numpy as np
    mesh = _load_mesh(_generate_mesh_if_needed("KCT_R1.csv", "kct"))
    elev = np.asarray(mesh["centerline"]["z_m"])
    seam_gap = float(elev[0] - elev[-1])
    assert abs(seam_gap) <= _SEAM_ELEV_TOLERANCE_M, (
        f"KCT_R1 seam elevation gap = {seam_gap:+.3f} m exceeds "
        f"tolerance — closed-loop smoothing regression"
    )


# ── G3: bounded width derivative ───────────────────────────────────────


def test_ok_r4_width_derivative_bounded():
    """G3: adjacent-bin width change |Δw| must be < 1m on > 99% of bins.
    Hand-traced gt is smooth; large jumps indicate per-bin discontinuity
    that produces visual fan/twist artifacts."""
    mesh = _load_mesh(_generate_mesh_if_needed("OK_R4.csv", "ok"))
    dL, dR = _per_bin_widths(mesh)
    jumps_L = np.abs(np.diff(dL))
    jumps_R = np.abs(np.diff(dR))
    assert np.percentile(jumps_L, 99) < 1.0, (
        f"OK_R4 LEFT p99 step = {np.percentile(jumps_L, 99):.2f}m — "
        "boundary has discontinuities"
    )
    assert np.percentile(jumps_R, 99) < 1.0, (
        f"OK_R4 RIGHT p99 step = {np.percentile(jumps_R, 99):.2f}m — "
        "boundary has discontinuities"
    )
