/**
 * chart_frame.js — JS companion for ChartFrame CSS component.
 *
 * Provides:
 *   ChartFrame.wrap(canvasId, options) — wrap canvas in ChartFrame markup
 *   ChartFrame.setState(frameEl, state) — loading|empty|error|ready
 *   ChartFrame.openDrawer(html) — open mobile bottom drawer
 *   ChartFrame.closeDrawer() — close drawer
 */
(function () {
    'use strict';

    var _lc = window.LifecycleHelpers.create();
    var _drawerEl = null;
    var _backdropEl = null;
    var _observer = null;

    /* ── Drawer (singleton, created on demand) ── */

    function _ensureDrawer() {
        if (_drawerEl) return;
        _backdropEl = document.createElement('div');
        _backdropEl.className = 'chart-drawer__backdrop';
        document.body.appendChild(_backdropEl);

        _drawerEl = document.createElement('div');
        _drawerEl.className = 'chart-drawer';
        _drawerEl.innerHTML = '<div class="chart-drawer__handle"></div><div class="chart-drawer__content"></div>';
        document.body.appendChild(_drawerEl);

        _lc.addListener(_backdropEl, 'click', closeDrawer);
    }

    function openDrawer(html) {
        _ensureDrawer();
        // Note: html is always generated by application code, not user input.
        // Callers are responsible for escaping any dynamic values via window.esc().
        _drawerEl.querySelector('.chart-drawer__content').innerHTML = html;
        requestAnimationFrame(function () {
            _drawerEl.classList.add('open');
            _backdropEl.classList.add('open');
        });
    }

    function closeDrawer() {
        if (!_drawerEl) return;
        _drawerEl.classList.remove('open');
        _backdropEl.classList.remove('open');
    }

    /* ── State management ── */

    function setState(frameEl, state) {
        if (typeof frameEl === 'string') {
            frameEl = document.getElementById(frameEl);
        }
        if (!frameEl) return;
        frameEl.classList.remove('chart-frame--loading', 'chart-frame--empty', 'chart-frame--error');
        if (state && state !== 'ready') {
            frameEl.classList.add('chart-frame--' + state);
        }
    }

    /* ── Wrap existing canvas ── */

    function wrap(canvasId, options) {
        options = options || {};
        var canvas = document.getElementById(canvasId);
        if (!canvas) return null;

        // Create frame wrapper
        var frame = document.createElement('div');
        frame.className = 'chart-frame';
        if (options.compact) frame.classList.add('chart-frame--compact');
        if (options.tall) frame.classList.add('chart-frame--tall');
        frame.id = canvasId + '-frame';

        // Header
        if (options.title) {
            var header = document.createElement('div');
            header.className = 'chart-frame__header';
            var title = document.createElement('span');
            title.className = 'chart-frame__title';
            title.textContent = options.title;
            header.appendChild(title);

            if (options.actions) {
                var actions = document.createElement('div');
                actions.className = 'chart-frame__actions';
                header.appendChild(actions);
            }
            frame.appendChild(header);
        }

        // Body (wraps the canvas)
        var body = document.createElement('div');
        body.className = 'chart-frame__body';
        if (options.emptyMessage) body.setAttribute('data-empty-message', options.emptyMessage);
        if (options.errorMessage) body.setAttribute('data-error-message', options.errorMessage);

        canvas.parentNode.insertBefore(frame, canvas);
        body.appendChild(canvas);
        frame.appendChild(body);

        // Set up ResizeObserver for auto-redraw
        if (window.ResizeObserver) {
            if (!_observer) {
                _observer = new ResizeObserver(function (entries) {
                    for (var i = 0; i < entries.length; i++) {
                        var c = entries[i].target.querySelector('canvas');
                        if (c && typeof c.__redraw === 'function') {
                            c.__redraw();
                        }
                    }
                });
            }
            _observer.observe(body);
        }

        return frame;
    }

    /* ── Dot navigation for card stack ── */

    function initDotNav(stackEl) {
        if (!stackEl) return;
        var frames = stackEl.querySelectorAll('.chart-frame');
        if (frames.length < 2) return;

        var nav = document.createElement('div');
        nav.className = 'chart-dot-nav';
        for (var i = 0; i < frames.length; i++) {
            var dot = document.createElement('span');
            dot.className = 'chart-dot-nav__dot';
            if (i === 0) dot.classList.add('active');
            nav.appendChild(dot);
        }
        stackEl.parentNode.insertBefore(nav, stackEl.nextSibling);

        var dots = nav.querySelectorAll('.chart-dot-nav__dot');
        _lc.addListener(stackEl, 'scroll', function () {
            var scrollLeft = stackEl.scrollLeft;
            var frameWidth = stackEl.offsetWidth;
            var idx = Math.round(scrollLeft / frameWidth);
            for (var j = 0; j < dots.length; j++) {
                dots[j].classList.toggle('active', j === idx);
            }
        }, { passive: true });
    }

    /* ── Destroy ── */

    function destroy() {
        closeDrawer();
        if (_drawerEl) {
            _drawerEl.remove();
            _drawerEl = null;
        }
        if (_backdropEl) {
            _backdropEl.remove();
            _backdropEl = null;
        }
        if (_observer) {
            _observer.disconnect();
            _observer = null;
        }
        _lc.destroyAll();
    }

    /* ── Public API ── */

    window.ChartFrame = {
        wrap: wrap,
        setState: setState,
        openDrawer: openDrawer,
        closeDrawer: closeDrawer,
        initDotNav: initDotNav,
        destroy: destroy
    };

    window.ModuleManager.register('chart_frame', {
        init: function () {},
        destroy: destroy
    });
})();
