"""Le Mans Ultimate (rFactor 2 engine) CSV telemetry adapter.

Handles CSV telemetry exports from Le Mans Ultimate / rFactor 2, including
files generated by shared memory dump tools and replay exports.

Detection
---------
Reads the first header line and looks for rFactor 2-specific column names
(``mLapStartET``, ``mPos``, ``mLocalVel``, ``mSteer``, ``mThrottle``,
``mBrake``, ``mGear``, ``mRPM``).  Requires at least 3 of these sentinels
for high confidence (0.85).

Parsing
-------
Maps rFactor 2 column names to canonical names defined in
``telemetry_tool.channel_registry``.  Applies unit conversions:

- Throttle/Brake: 0.0-1.0 fraction to 0-100 percentage
- Steering: -1..+1 normalized to approximate degrees (* 180)
- Speed: computed as magnitude of mLocalVel.x/y/z
- Position: Y-up convention (mPos.y = altitude)
- Time: synthesised from row index at 90 Hz if no time column
"""

from __future__ import annotations

import logging
import math
from pathlib import Path
from typing import Final, Optional

import numpy as np
import pandas as pd

from telemetry_tool.adapters.base import BaseAdapter

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

_DEFAULT_SAMPLE_RATE_HZ: Final[float] = 90.0

_ENCODINGS: Final[tuple[str, ...]] = ("utf-8", "utf-8-sig", "latin-1", "cp1252")

#: Header sentinels used for format detection.
_LMU_SENTINELS: Final[frozenset[str]] = frozenset({
    "mLapStartET", "mPos", "mLocalVel", "mSteer",
    "mThrottle", "mBrake", "mGear", "mRPM",
})

# ---------------------------------------------------------------------------
# Column mapping: rFactor 2 raw -> (canonical_name, conversion_func | None)
# ---------------------------------------------------------------------------

_NUMERIC = lambda s: pd.to_numeric(s, errors="coerce")  # noqa: E731
_SCALE_01_TO_PCT = lambda s: pd.to_numeric(s, errors="coerce") * 100.0  # noqa: E731
_STEER_TO_DEG = lambda s: pd.to_numeric(s, errors="coerce") * 180.0  # noqa: E731

# (rF2 column, canonical name, conversion or None)
_COLUMN_MAP: Final[list[tuple[str, str, object]]] = [
    # Position (rF2 Y-up: mPos.x=horizontal, mPos.z=horizontal, mPos.y=vertical)
    ("mPos.x",           "pos_x_m",             _NUMERIC),
    ("mPos.z",           "pos_y_m",             _NUMERIC),
    ("mPos.y",           "altitude_m",          _NUMERIC),

    # Acceleration
    ("mLocalAccel.x",   "accel_long_mps2",      _NUMERIC),
    ("mLocalAccel.y",   "accel_lat_mps2",       _NUMERIC),

    # Controls
    ("mSteer",          "steering_angle_deg",    _STEER_TO_DEG),
    ("mThrottle",       "throttle_pct",          _SCALE_01_TO_PCT),
    ("mBrake",          "brake_pct",             _SCALE_01_TO_PCT),

    # Engine
    ("mGear",           "gear",                  _NUMERIC),
    ("mRPM",            "rpm",                   _NUMERIC),

    # Distance
    ("mLapDist",        "distance_m",            _NUMERIC),
]

#: All raw column names from the mapping (for extended detection scoring).
_LMU_RAW_NAMES: Final[frozenset[str]] = frozenset(
    raw for raw, _, _ in _COLUMN_MAP
)

#: Tire temperature columns (rF2 convention: 0=FL, 1=FR, 2=RL, 3=RR).
_TIRE_TEMP_MAP: Final[list[tuple[str, str]]] = [
    ("mWheels[0].mTemperature", "tire_temp_fl"),
    ("mWheels[1].mTemperature", "tire_temp_fr"),
    ("mWheels[2].mTemperature", "tire_temp_rl"),
    ("mWheels[3].mTemperature", "tire_temp_rr"),
]

#: Tire pressure columns.
_TIRE_PRESSURE_MAP: Final[list[tuple[str, str]]] = [
    ("mWheels[0].mPressure", "tire_pressure_fl"),
    ("mWheels[1].mPressure", "tire_pressure_fr"),
    ("mWheels[2].mPressure", "tire_pressure_rl"),
    ("mWheels[3].mPressure", "tire_pressure_rr"),
]

#: Tire wear columns.
_TIRE_WEAR_MAP: Final[list[tuple[str, str]]] = [
    ("mWheels[0].mWear", "tire_wear_fl"),
    ("mWheels[1].mWear", "tire_wear_fr"),
    ("mWheels[2].mWear", "tire_wear_rl"),
    ("mWheels[3].mWear", "tire_wear_rr"),
]


# ---------------------------------------------------------------------------
# Adapter
# ---------------------------------------------------------------------------
class LMUAdapter(BaseAdapter):
    """Adapter for Le Mans Ultimate / rFactor 2 CSV telemetry exports."""

    FORMAT_NAME: str = "lmu"
    EXTENSIONS: list[str] = [".csv"]

    def __init__(self) -> None:
        self._channels: list[str] = []
        self._metadata: dict = {}

    # ------------------------------------------------------------------
    # detect
    # ------------------------------------------------------------------
    @staticmethod
    def detect(file_path: str) -> float:
        """Return confidence 0.0-1.0 that *file_path* is an LMU/rF2 CSV.

        Reads only the first header line.  Requires at least 3 of the
        sentinel column names for high confidence (0.85).

        Returns 0.0 on any I/O error or non-CSV file.
        """
        try:
            path = Path(file_path)
            if not path.exists():
                return 0.0

            suffix = path.suffix.lower()
            if suffix not in (".csv", ".txt", ""):
                return 0.0

            header_line = _read_header_line(path)
            if not header_line:
                return 0.0

            return _score_header(header_line)
        except Exception:
            logger.debug(
                "LMUAdapter.detect() failed for %s", file_path,
                exc_info=True,
            )
            return 0.0

    # ------------------------------------------------------------------
    # parse
    # ------------------------------------------------------------------
    def parse(
        self,
        file_path: str,
        progress_cb: Optional[object] = None,
    ) -> pd.DataFrame:
        """Parse *file_path* into a canonical DataFrame.

        Maps rFactor 2 columns to canonical names, applies unit
        conversions, computes speed from velocity components, and
        synthesises time_s if absent.
        """
        df = _read_lmu_csv(file_path)

        # Store raw metadata before column renaming.
        self._metadata = _extract_metadata(df, file_path)

        # Apply column mapping and conversions.
        df = _rename_and_convert(df)

        # Compute speed from velocity components if not already present.
        df = _compute_speed(df)

        # Synthesise time_s from row index if not already present.
        if "time_s" not in df.columns:
            df = _synthesise_time(df)

        # Store canonical channel list.
        from telemetry_tool.channel_registry import CHANNELS
        self._channels = [col for col in df.columns if col in CHANNELS]

        return df

    # ------------------------------------------------------------------
    # metadata
    # ------------------------------------------------------------------
    def metadata(self) -> dict:
        """Return session metadata extracted during parsing."""
        return dict(self._metadata)

    # ------------------------------------------------------------------
    # available_channels
    # ------------------------------------------------------------------
    def available_channels(self) -> list[str]:
        """Return canonical channel names present after parsing."""
        return list(self._channels)


# ---------------------------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------------------------

def _read_header_line(path: Path) -> str:
    """Read the first non-empty line from *path* with encoding fallback."""
    for enc in _ENCODINGS:
        try:
            with path.open(encoding=enc) as fh:
                for line in fh:
                    stripped = line.strip()
                    if stripped:
                        return stripped
            return ""
        except UnicodeDecodeError:
            continue
    return ""


def _score_header(header_line: str) -> float:
    """Score how likely *header_line* represents an LMU/rF2 CSV header.

    Returns a confidence between 0.0 and 1.0.
    """
    # Determine delimiter.
    delim = ";" if header_line.count(";") > header_line.count(",") else ","
    cells = {c.strip() for c in header_line.split(delim)}

    sentinel_hits = len(cells & _LMU_SENTINELS)

    if sentinel_hits >= 3:
        return 0.85
    elif sentinel_hits == 2:
        return 0.5
    elif sentinel_hits == 1:
        return 0.3
    return 0.0


def _read_lmu_csv(file_path: str) -> pd.DataFrame:
    """Read an LMU/rF2 CSV into a raw DataFrame.

    Tries multiple encodings.  Returns the DataFrame with original column
    names (no renaming).
    """
    path = Path(file_path)
    for enc in _ENCODINGS:
        try:
            df = pd.read_csv(path, encoding=enc)
            # Strip whitespace from column names.
            df.columns = [c.strip() for c in df.columns]
            return df
        except UnicodeDecodeError:
            continue
    # Last resort: replace bad characters.
    df = pd.read_csv(path, encoding="utf-8", errors="replace")
    df.columns = [c.strip() for c in df.columns]
    return df


def _extract_metadata(df: pd.DataFrame, file_path: str) -> dict:
    """Extract metadata from the raw DataFrame and file path."""
    meta: dict = {"source": "lmu", "format": "lmu"}

    path = Path(file_path)
    meta["file_name"] = path.name

    # rF2 exports sometimes include vehicle/track info as columns.
    for col in ("mVehicleName", "mTrackName"):
        if col in df.columns:
            vals = df[col].dropna().unique()
            if len(vals) > 0:
                meta[col] = str(vals[0])

    return meta


def _rename_and_convert(df: pd.DataFrame) -> pd.DataFrame:
    """Rename LMU columns to canonical names and apply conversions."""
    columns_set = set(df.columns)
    rename_map: dict[str, str] = {}
    conversions: dict[str, object] = {}
    claimed_canonical: set[str] = set()

    for raw_name, canonical, convert_fn in _COLUMN_MAP:
        if canonical in claimed_canonical:
            continue
        if raw_name in columns_set:
            rename_map[raw_name] = canonical
            claimed_canonical.add(canonical)
            if convert_fn is not None:
                conversions[canonical] = convert_fn

    # Handle time columns: mElapsedTime or mLapStartET -> time_s.
    for time_col in ("mElapsedTime", "mLapStartET"):
        if time_col in columns_set and "time_s" not in claimed_canonical:
            rename_map[time_col] = "time_s"
            claimed_canonical.add("time_s")
            conversions["time_s"] = _NUMERIC
            break

    # Handle lap number: mLapNumber or mTotalLaps.
    for lap_col in ("mLapNumber", "mTotalLaps"):
        if lap_col in columns_set and "lap_number" not in claimed_canonical:
            rename_map[lap_col] = "lap_number"
            claimed_canonical.add("lap_number")
            conversions["lap_number"] = _NUMERIC
            break

    # Rename columns.
    df = df.rename(columns=rename_map)

    # Apply conversions.
    for canonical, convert_fn in conversions.items():
        if canonical in df.columns:
            df[canonical] = convert_fn(df[canonical])

    # Map tire temperature columns.
    for raw_name, canonical in _TIRE_TEMP_MAP:
        if raw_name in columns_set and canonical not in claimed_canonical:
            df[canonical] = pd.to_numeric(df[raw_name], errors="coerce")
            claimed_canonical.add(canonical)

    # Map tire pressure columns.
    for raw_name, canonical in _TIRE_PRESSURE_MAP:
        if raw_name in columns_set and canonical not in claimed_canonical:
            df[canonical] = pd.to_numeric(df[raw_name], errors="coerce")
            claimed_canonical.add(canonical)

    # Map tire wear columns.
    for raw_name, canonical in _TIRE_WEAR_MAP:
        if raw_name in columns_set and canonical not in claimed_canonical:
            df[canonical] = pd.to_numeric(df[raw_name], errors="coerce")
            claimed_canonical.add(canonical)

    return df


def _compute_speed(df: pd.DataFrame) -> pd.DataFrame:
    """Compute speed_mps as magnitude of local velocity components."""
    if "speed_mps" in df.columns:
        return df

    vel_cols = ["mLocalVel.x", "mLocalVel.y", "mLocalVel.z"]
    present = [c for c in vel_cols if c in df.columns]

    if not present:
        return df

    # Use available components; missing ones default to 0.
    vx = pd.to_numeric(df["mLocalVel.x"], errors="coerce").fillna(0.0) if "mLocalVel.x" in df.columns else 0.0
    vy = pd.to_numeric(df["mLocalVel.y"], errors="coerce").fillna(0.0) if "mLocalVel.y" in df.columns else 0.0
    vz = pd.to_numeric(df["mLocalVel.z"], errors="coerce").fillna(0.0) if "mLocalVel.z" in df.columns else 0.0

    df["speed_mps"] = np.sqrt(vx**2 + vy**2 + vz**2)
    return df


def _synthesise_time(df: pd.DataFrame) -> pd.DataFrame:
    """Synthesise time_s from row index at the default sample rate."""
    period = 1.0 / _DEFAULT_SAMPLE_RATE_HZ
    df["time_s"] = np.arange(len(df), dtype=np.float64) * period
    return df
