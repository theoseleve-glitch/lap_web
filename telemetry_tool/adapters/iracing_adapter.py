"""iRacing CSV/IBT adapter.

Handles telemetry CSV exports from iRacing, including files generated by
iSpeed, exported from replay, or produced by other iRacing telemetry tools.

Detection
---------
Reads the first header line and looks for iRacing-specific column names
(``Lap``, ``Speed``, ``Throttle``, ``Brake``, ``RPM``,
``SteeringWheelAngle``).  Requires at least 3 of these sentinels for high
confidence (0.9).

Parsing
-------
Maps iRacing column names to canonical names defined in
``telemetry_tool.channel_registry``.  Applies unit conversions:

- Throttle/Brake/Clutch: 0.0-1.0 fraction to 0-100 percentage
- SteeringWheelAngle: radians to degrees
- YawRate: rad/s to deg/s
- FuelLevel: litres to kg (density 0.75 kg/L)
- Time: synthesised from row index at 60 Hz if no ``SessionTime`` column

Tire temperature zones are mapped respecting the iRacing convention where
for left-side tires CL = outer and CR = inner, and for right-side tires
CL = inner and CR = outer.
"""

from __future__ import annotations

import logging
import math
from pathlib import Path
from typing import Final, Optional

import numpy as np
import pandas as pd

from telemetry_tool.adapters.base import BaseAdapter

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

_RAD_TO_DEG: Final[float] = 180.0 / math.pi
_FUEL_DENSITY_KG_PER_L: Final[float] = 0.75
_DEFAULT_SAMPLE_RATE_HZ: Final[float] = 60.0

_ENCODINGS: Final[tuple[str, ...]] = ("utf-8", "utf-8-sig", "latin-1", "cp1252")

#: Header sentinels used for format detection.  If at least 3 of these
#: appear in the header row, we classify the file as iRacing with high
#: confidence.
_IRACING_SENTINELS: Final[frozenset[str]] = frozenset({
    "Lap", "Speed", "Throttle", "Brake", "RPM", "SteeringWheelAngle",
})

# ---------------------------------------------------------------------------
# Column mapping: iRacing raw -> (canonical_name, conversion_func | None)
#
# conversion_func receives a pd.Series and returns a pd.Series.
# None means no conversion (use as-is).
# ---------------------------------------------------------------------------

_SCALE_01_TO_PCT = lambda s: pd.to_numeric(s, errors="coerce") * 100.0  # noqa: E731
_RAD_TO_DEG_FN = lambda s: pd.to_numeric(s, errors="coerce") * _RAD_TO_DEG  # noqa: E731
_LITRE_TO_KG = lambda s: pd.to_numeric(s, errors="coerce") * _FUEL_DENSITY_KG_PER_L  # noqa: E731
_NUMERIC = lambda s: pd.to_numeric(s, errors="coerce")  # noqa: E731

# (iRacing column, canonical name, conversion or None)
_COLUMN_MAP: Final[list[tuple[str, str, object]]] = [
    # Tier 1 -- Essential
    ("Lap",              "lap_number",       _NUMERIC),
    ("LapDist",          "distance_m",       _NUMERIC),
    ("Speed",            "speed_mps",        _NUMERIC),
    ("Lat",              "lat_deg",          _NUMERIC),
    ("Lon",              "lon_deg",          _NUMERIC),
    ("Alt",              "altitude_m",       _NUMERIC),

    # Tier 2 -- Standard (IMU)
    ("LatAccel",         "accel_lat_mps2",   _NUMERIC),
    ("LonAccel",         "accel_long_mps2",  _NUMERIC),
    ("YawRate",          "yaw_rate_dps",     _RAD_TO_DEG_FN),

    # Tier 3 -- Controls
    ("Throttle",         "throttle_pct",     _SCALE_01_TO_PCT),
    ("Brake",            "brake_pct",        _SCALE_01_TO_PCT),
    ("Clutch",           "clutch_pct",       _SCALE_01_TO_PCT),
    ("Gear",             "gear",             _NUMERIC),
    ("RPM",              "rpm",              _NUMERIC),
    ("SteeringWheelAngle", "steering_angle_deg", _RAD_TO_DEG_FN),

    # Tier 4 -- Tire temperatures (zone mapping)
    # Left-side: CL = outer, CR = inner
    ("LFtempCL",        "tire_temp_fl_o",   _NUMERIC),
    ("LFtempCM",        "tire_temp_fl_m",   _NUMERIC),
    ("LFtempCR",        "tire_temp_fl_i",   _NUMERIC),
    ("LRtempCL",        "tire_temp_rl_o",   _NUMERIC),
    ("LRtempCM",        "tire_temp_rl_m",   _NUMERIC),
    ("LRtempCR",        "tire_temp_rl_i",   _NUMERIC),
    # Right-side: CL = inner, CR = outer
    ("RFtempCL",        "tire_temp_fr_i",   _NUMERIC),
    ("RFtempCM",        "tire_temp_fr_m",   _NUMERIC),
    ("RFtempCR",        "tire_temp_fr_o",   _NUMERIC),
    ("RRtempCL",        "tire_temp_rr_i",   _NUMERIC),
    ("RRtempCM",        "tire_temp_rr_m",   _NUMERIC),
    ("RRtempCR",        "tire_temp_rr_o",   _NUMERIC),

    # Tire pressure (kPa, no conversion)
    ("LFpressure",      "tire_pressure_fl", _NUMERIC),
    ("RFpressure",      "tire_pressure_fr", _NUMERIC),
    ("LRpressure",      "tire_pressure_rl", _NUMERIC),
    ("RRpressure",      "tire_pressure_rr", _NUMERIC),

    # Wheel speed (m/s, no conversion)
    ("LFspd",           "wheel_speed_fl",   _NUMERIC),
    ("RFspd",           "wheel_speed_fr",   _NUMERIC),
    ("LRspd",           "wheel_speed_rl",   _NUMERIC),
    ("RRspd",           "wheel_speed_rr",   _NUMERIC),

    # Fuel
    ("FuelLevel",       "fuel_kg",          _LITRE_TO_KG),

    # Environment
    ("AirTemp",         "air_temp",         _NUMERIC),
    ("TrackTemp",       "track_temp",       _NUMERIC),
]

# Pre-compute raw column name set for the mapping.
_IRACING_RAW_NAMES: Final[frozenset[str]] = frozenset(
    raw for raw, _, _ in _COLUMN_MAP
)

# Tire wear columns: iRacing provides 3 zones per corner (L, M, R).
# We average the 3 zones into a single value per corner.
_TIRE_WEAR_MAP: Final[dict[str, list[str]]] = {
    "tire_wear_fl": ["LFwearL", "LFwearM", "LFwearR"],
    "tire_wear_fr": ["RFwearL", "RFwearM", "RFwearR"],
    "tire_wear_rl": ["LRwearL", "LRwearM", "LRwearR"],
    "tire_wear_rr": ["RRwearL", "RRwearM", "RRwearR"],
}

# Aggregate tire temperature: average of inner/middle/outer per corner.
_TIRE_TEMP_AGG: Final[dict[str, list[str]]] = {
    "tire_temp_fl": ["tire_temp_fl_i", "tire_temp_fl_m", "tire_temp_fl_o"],
    "tire_temp_fr": ["tire_temp_fr_i", "tire_temp_fr_m", "tire_temp_fr_o"],
    "tire_temp_rl": ["tire_temp_rl_i", "tire_temp_rl_m", "tire_temp_rl_o"],
    "tire_temp_rr": ["tire_temp_rr_i", "tire_temp_rr_m", "tire_temp_rr_o"],
}


# ---------------------------------------------------------------------------
# Adapter
# ---------------------------------------------------------------------------
class IRacingAdapter(BaseAdapter):
    """Adapter for iRacing CSV telemetry exports."""

    FORMAT_NAME: str = "iracing"
    EXTENSIONS: list[str] = [".csv", ".txt"]

    def __init__(self) -> None:
        self._channels: list[str] = []
        self._metadata: dict = {}

    # ------------------------------------------------------------------
    # detect
    # ------------------------------------------------------------------
    @staticmethod
    def detect(file_path: str) -> float:
        """Return confidence 0.0-1.0 that *file_path* is an iRacing CSV.

        Reads only the first header line.  Requires at least 3 of the
        sentinel column names for high confidence (0.9).

        Returns 0.0 on any I/O error or non-CSV file.
        """
        try:
            path = Path(file_path)
            if not path.exists():
                return 0.0

            suffix = path.suffix.lower()
            if suffix not in (".csv", ".txt", ""):
                return 0.0

            header_line = _read_header_line(path)
            if not header_line:
                return 0.0

            return _score_header(header_line)
        except Exception:
            logger.debug(
                "IRacingAdapter.detect() failed for %s", file_path,
                exc_info=True,
            )
            return 0.0

    # ------------------------------------------------------------------
    # parse
    # ------------------------------------------------------------------
    def parse(
        self,
        file_path: str,
        progress_cb: Optional[object] = None,
    ) -> pd.DataFrame:
        """Parse *file_path* into a canonical DataFrame.

        Maps iRacing columns to canonical names, applies unit conversions,
        synthesises time_s if absent, and computes aggregate tire
        temperatures and wear values.
        """
        df = _read_iracing_csv(file_path)

        # Store raw metadata before column renaming.
        self._metadata = _extract_metadata(df, file_path)

        # Apply column mapping and conversions.
        df = _rename_and_convert(df)

        # Synthesise time_s from row index if not already present.
        if "time_s" not in df.columns:
            df = _synthesise_time(df)

        # Compute aggregate tire temperatures.
        df = _compute_tire_temp_aggregates(df)

        # Compute average tire wear per corner.
        df = _compute_tire_wear(df)

        # Store canonical channel list.
        from telemetry_tool.channel_registry import CHANNELS
        self._channels = [col for col in df.columns if col in CHANNELS]

        return df

    # ------------------------------------------------------------------
    # metadata
    # ------------------------------------------------------------------
    def metadata(self) -> dict:
        """Return session metadata extracted during parsing."""
        return dict(self._metadata)

    # ------------------------------------------------------------------
    # available_channels
    # ------------------------------------------------------------------
    def available_channels(self) -> list[str]:
        """Return canonical channel names present after parsing."""
        return list(self._channels)


# ---------------------------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------------------------

def _read_header_line(path: Path) -> str:
    """Read the first non-empty line from *path* with encoding fallback."""
    for enc in _ENCODINGS:
        try:
            with path.open(encoding=enc) as fh:
                for line in fh:
                    stripped = line.strip()
                    if stripped:
                        return stripped
            return ""
        except UnicodeDecodeError:
            continue
    return ""


def _score_header(header_line: str) -> float:
    """Score how likely *header_line* represents an iRacing CSV header.

    Returns a confidence between 0.0 and 1.0.
    """
    # Determine delimiter.
    delim = ";" if header_line.count(";") > header_line.count(",") else ","
    cells = {c.strip() for c in header_line.split(delim)}

    sentinel_hits = len(cells & _IRACING_SENTINELS)

    if sentinel_hits >= 3:
        # High confidence: 3+ sentinel columns.
        return 0.9
    elif sentinel_hits == 2:
        return 0.6
    elif sentinel_hits == 1:
        # One sentinel could be coincidental; check for more iRacing columns.
        extra = len(cells & _IRACING_RAW_NAMES) - sentinel_hits
        if extra >= 2:
            return 0.5
        return 0.3
    return 0.0


def _read_iracing_csv(file_path: str) -> pd.DataFrame:
    """Read an iRacing CSV into a raw DataFrame.

    Tries multiple encodings.  Returns the DataFrame with original column
    names (no renaming).
    """
    path = Path(file_path)
    for enc in _ENCODINGS:
        try:
            df = pd.read_csv(path, encoding=enc)
            # Strip whitespace from column names.
            df.columns = [c.strip() for c in df.columns]
            return df
        except UnicodeDecodeError:
            continue
    # Last resort: replace bad characters.
    df = pd.read_csv(path, encoding="utf-8", errors="replace")
    df.columns = [c.strip() for c in df.columns]
    return df


def _extract_metadata(df: pd.DataFrame, file_path: str) -> dict:
    """Extract metadata from the raw DataFrame and file path."""
    meta: dict = {"source": "iracing"}

    # File-level info.
    path = Path(file_path)
    meta["file_name"] = path.name

    # Try to infer car/track from column data or file name.
    # iRacing exports sometimes include these as columns.
    for col in ("CarName", "TrackName", "SessionType"):
        if col in df.columns:
            vals = df[col].dropna().unique()
            if len(vals) > 0:
                meta[col.lower()] = str(vals[0])

    return meta


def _rename_and_convert(df: pd.DataFrame) -> pd.DataFrame:
    """Rename iRacing columns to canonical names and apply conversions."""
    columns_set = set(df.columns)
    rename_map: dict[str, str] = {}
    conversions: dict[str, object] = {}
    claimed_canonical: set[str] = set()

    for raw_name, canonical, convert_fn in _COLUMN_MAP:
        if canonical in claimed_canonical:
            continue
        if raw_name in columns_set:
            rename_map[raw_name] = canonical
            claimed_canonical.add(canonical)
            if convert_fn is not None:
                conversions[canonical] = convert_fn

    # Handle SessionTime -> time_s (direct mapping, no conversion).
    if "SessionTime" in columns_set and "time_s" not in claimed_canonical:
        rename_map["SessionTime"] = "time_s"
        claimed_canonical.add("time_s")
        conversions["time_s"] = _NUMERIC

    # Rename columns.
    df = df.rename(columns=rename_map)

    # Apply conversions.
    for canonical, convert_fn in conversions.items():
        if canonical in df.columns:
            df[canonical] = convert_fn(df[canonical])

    return df


def _synthesise_time(df: pd.DataFrame) -> pd.DataFrame:
    """Synthesise time_s from row index at the default sample rate."""
    period = 1.0 / _DEFAULT_SAMPLE_RATE_HZ
    df["time_s"] = np.arange(len(df), dtype=np.float64) * period
    return df


def _compute_tire_temp_aggregates(df: pd.DataFrame) -> pd.DataFrame:
    """Compute average 4-corner tire temperatures from zone columns."""
    for agg_name, zone_cols in _TIRE_TEMP_AGG.items():
        present = [c for c in zone_cols if c in df.columns]
        if present:
            df[agg_name] = df[present].mean(axis=1)
    return df


def _compute_tire_wear(df: pd.DataFrame) -> pd.DataFrame:
    """Compute average tire wear per corner from 3-zone wear columns.

    iRacing provides LFwearL, LFwearM, LFwearR (and similar for other
    corners).  We average the available zones.

    Note: If only the ``L`` zone column is present (as in partial exports),
    we still produce a value from that single column.
    """
    columns_set = set(df.columns)
    for canonical, raw_cols in _TIRE_WEAR_MAP.items():
        present = [c for c in raw_cols if c in columns_set]
        if present:
            zone_data = df[present].apply(pd.to_numeric, errors="coerce")
            df[canonical] = zone_data.mean(axis=1)
    return df
